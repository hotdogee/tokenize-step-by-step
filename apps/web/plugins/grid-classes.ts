/**
 * `gridClasses()` — writes `src/board/grid-classes.css` (generated, gitignored): `.c1…c128` set `grid-column-start`,
 * `.s1…s128` set `grid-column-end: span n` (and `--span: n`, the default width of a char box and a chip's id room,
 * board.css), and `.k8…k64` set the board's column count `--k`. Under the strict CSP the board cannot use inline styles,
 * so every cell is placed with two classes (AD-15; marker columns are full columns, AD-25) and the grid takes its K from
 * a class — which also keeps the server-rendered first paint (PA-15) free of `style` attributes. The board's K stays
 * ≤ 64 (src/board/geometry.ts); the comparison table (PA-19) places its cells in a window of up to 128 columns, rebased
 * to the window start, and reads its column count from the same `.k<n>` classes up to 64 columns.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import type { Plugin } from 'vite';

/** The smallest and the largest K (05 §3.3: K = clamp(8, …, 64)). */
export const MIN_COLUMNS = 8;
export const MAX_K = 64;
/** Placement classes: the comparison table's window (PA-19, src/compare/compare-window.ts) is at most 128 columns. */
export const MAX_COLUMNS = 128;

/** The generated stylesheet: placement classes for columns 1…`maxColumns`, K classes for 8…`maxK`. */
export function gridClassesCss(maxColumns: number = MAX_COLUMNS, maxK: number = MAX_K): string {
  const lines = ['/* Generated by apps/web/plugins/grid-classes.ts — do not edit. */'];
  for (let n = 1; n <= maxColumns; n++) lines.push(`.c${String(n)} { grid-column-start: ${String(n)}; }`);
  for (let n = 1; n <= maxColumns; n++)
    lines.push(`.s${String(n)} { grid-column-end: span ${String(n)}; --span: ${String(n)}; }`);
  for (let n = MIN_COLUMNS; n <= maxK; n++) lines.push(`.k${String(n)} { --k: ${String(n)}; }`);
  return `${lines.join('\n')}\n`;
}

/** Writes `file` only when its content would change, so dev watchers are not retriggered. */
async function writeIfChanged(file: string, content: string): Promise<void> {
  const current = await readFile(file, 'utf8').catch(() => null);
  if (current === content) return;
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, content, 'utf8');
}

export interface GridClassesOptions {
  /** Output file, relative to the Vite root. */
  readonly out?: string;
}

export function gridClasses(options: GridClassesOptions = {}): Plugin {
  let out = '';
  return {
    name: 'tsbs:grid-classes',
    configResolved(config) {
      out = resolve(config.root, options.out ?? 'src/board/grid-classes.css');
    },
    async buildStart() {
      await writeIfChanged(out, gridClassesCss());
    },
  };
}
