"""Render ``docs/licenses/README.md`` from ``tools/oracle/manifest.json``.

The README summarises, per asset, the SPDX identifier, ship intent, plain-
language obligations and links to the verbatim snapshots that
``fetch_vocab.py`` copied into ``docs/licenses/<asset-id>/``. Output is
deterministic; re-run after editing the manifest.

Usage (from the repository root)::

    uv run --project tools/oracle tools/oracle/render_license_docs.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from oracle_lib import fsio, paths
from oracle_lib import manifest as mf

README_PATH = paths.LICENSES_DIR / "README.md"
INTENT_LEGEND = {
    "ship": "a file derived from this asset is planned for the public site",
    "oracle-only": "used locally or in CI as a reference implementation only; never redistributed",
    "phase-2": "a candidate for a later phase; needs owner sign-off before shipping",
}


def _md(text: str) -> str:
    """Escape free text so literal ``<token>`` strings are not read as HTML."""
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _cell(text: str) -> str:
    return _md(text).replace("|", "\\|")


def _snapshot_links(asset: mf.Asset) -> list[str]:
    links = []
    for entry in asset["files"]:
        if entry["role"] in mf.SNAPSHOT_ROLES:
            rel = f"{asset['id']}/{entry['name']}"
            links.append(f"[{entry['name']}]({rel}) ({entry['role']})")
    return links


def render(manifest: dict) -> str:
    """Return the README text for ``manifest``."""
    out = [
        "# Third-party licences for tokenizer vocabularies",
        "",
        "<!-- Generated by tools/oracle/render_license_docs.py from tools/oracle/manifest.json."
        " Do not edit by hand. -->",
        "",
        "Each folder holds verbatim licence, notice and policy files fetched at the pinned upstream revision",
        "recorded in `tools/oracle/manifest.json` (re-fetch with `tools/oracle/fetch_vocab.py`).",
        "The one exception is a `.txt` file whose manifest source type is `html-text`: it is a deterministic",
        "plain-text extraction of the HTML page snapshotted next to it (e.g. the Gemma Terms of Use).",
        "Obligations are plain-language summaries for planning, not legal advice; the snapshot text governs.",
        "",
        "Ship intent:",
        "",
    ]
    out += [f"- `{k}`: {v}." for k, v in INTENT_LEGEND.items()]
    out += ["", "| Asset | Lab | SPDX | Ship intent |", "|---|---|---|---|"]
    for asset in manifest["assets"]:
        out.append(
            f"| [{asset['id']}](#{asset['id'].replace('.', '').lower()}) | {_cell(asset['lab'])} "
            f"| `{asset['license']['spdx']}` | `{asset['shipIntent']}` |"
        )
    for asset in manifest["assets"]:
        lic = asset["license"]
        ship_note = f" ({_md(asset['shipNote'])})" if asset.get("shipNote") else ""
        out += [
            "",
            f"## {asset['id']}",
            "",
            _md(asset["description"]),
            "",
            f"- **Lab:** {asset['lab']}",
            f"- **SPDX:** `{lic['spdx']}`",
            f"- **Ship intent:** `{asset['shipIntent']}`{ship_note}",
            f"- **Licence source (pinned):** <{lic['sourceUrl']}>",
            f"- **Snapshots:** {', '.join(_snapshot_links(asset))}",
            "- **Obligations:**",
        ]
        out += [f"  - {_md(item)}" for item in lic["obligations"]]
        out += ["", f"Provenance notes: {_md(asset['notes'])}"]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--manifest", type=Path, default=paths.MANIFEST_PATH)
    parser.add_argument("--check", action="store_true", help="fail if the README is out of date")
    args = parser.parse_args(argv)

    text = render(mf.load(args.manifest)).encode("utf-8")
    if args.check:
        current = README_PATH.read_bytes() if README_PATH.exists() else b""
        if current != text:
            print(f"{paths.repo_relative(README_PATH)} is out of date; re-run without --check", file=sys.stderr)
            return 1
        print(f"{paths.repo_relative(README_PATH)} is up to date")
        return 0
    changed = fsio.write_bytes_if_changed(README_PATH, text)
    print(f"{paths.repo_relative(README_PATH)} {'written' if changed else 'unchanged'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
